import { test, expect } from '@playwright/test'
import { createHash } from 'crypto'
import { mkdtempSync, mkdirSync, readFileSync } from 'fs'
import { join } from 'path'
import ExcelJS from 'exceljs'
import { launchApp, teardownApp, type TestContext } from './electron.setup'

test('real audit review keeps decisions, filters a shared report snapshot and protects the source', async ({}, testInfo) => {
  const root = join(__dirname,'..','tmp','e2e','audit-workspace')
  mkdirSync(root,{recursive:true})
  const output = mkdtempSync(join(root,'run-'))
  const source = join(output,'quarterly-review.xlsx')
  const book = new ExcelJS.Workbook()
  const first = book.addWorksheet('Revenue')
  first.getCell('A1').value = 'Quarterly cash review'
  first.getCell('B2').value = { formula:'B2+1', result:101 }
  first.getCell('B3').value = 'synthetic@example.test'
  const second = book.addWorksheet('Costs')
  second.getCell('AA80').value = { formula:'AA80+1', result:202 }
  await book.xlsx.writeFile(source)
  const hash = createHash('sha256').update(readFileSync(source)).digest('hex')
  let ctx: TestContext | undefined
  try {
    ctx = await launchApp()
    const { app,page } = ctx
    await app.evaluate(({ BrowserWindow }) => { const win=BrowserWindow.getAllWindows()[0]; win.setSize(1440,900) })
    await page.getByTestId('home-task-audit').click()
    await app.evaluate(({ dialog },path) => { dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]}) },source)
    await page.getByTestId('dropzone-browse-btn').click()
    await expect(page.getByTestId('audit-workspace')).toBeVisible({timeout:30000})
    await expect(page.getByTestId('results-protection-tab')).toHaveCount(0)
    await expect(page.getByTestId('review-inspector')).toBeVisible()
    const distant=page.locator('.aw-issue[data-sheet-name="Costs"][data-cell-address="AA80"]')
    await distant.click()
    await expect(page.locator('.sheet-tab.active')).toHaveText('Costs')
    await expect(page.getByTestId('preview-range')).toHaveText('S68:AR117')
    await expect(page.locator('[data-cell="AA80"]')).toHaveClass(/selected-cell/)
    await expect(page.getByTestId('review-cached-value')).toHaveText('202')
    await page.getByRole('radio',{name:'Confirmed issue',exact:true}).check()
    await page.getByTestId('review-note').fill('Checked against the signed quarterly schedule.')
    await page.getByTestId('review-filter').selectOption('confirmed')
    await expect(page.locator('.aw-issue')).toHaveCount(1)
    await page.getByTestId('review-filter').selectOption('all')
    await page.locator('.aw-issue[data-sheet-name="Revenue"][data-cell-address="B2"]').click()
    await page.getByRole('radio',{name:'Not applicable',exact:true}).check()
    await distant.click()
    await expect(page.getByTestId('review-note')).toHaveValue('Checked against the signed quarterly schedule.')
    await page.getByTestId('sidebar-nav-settings').click()
    await page.getByTestId('sidebar-nav-audit').click()
    await distant.click()
    await expect(page.getByRole('radio',{name:'Confirmed issue',exact:true})).toBeChecked()
    await expect(page.getByTestId('review-note')).toHaveValue('Checked against the signed quarterly schedule.')
    await page.screenshot({path:testInfo.outputPath('workspace-light.png'),animations:'disabled'})
    await page.getByTestId('theme-toggle').click()
    await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
    await page.screenshot({path:testInfo.outputPath('workspace-dark.png'),animations:'disabled'})
    await page.getByTestId('export-btn').click()
    const preview=page.getByRole('dialog')
    await expect(preview.locator('tbody tr')).toHaveCount(2)
    await expect(preview).toContainText('Not applicable')
    await page.getByTestId('export-scope').selectOption('confirmed')
    await expect(preview.locator('tbody tr')).toHaveCount(1)
    await expect(page.getByTestId('export-scope-summary')).toHaveText('1 included · 1 excluded')
    const html=join(output,'review.html')
    await app.evaluate(({dialog},path)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:path})},html)
    await page.getByTestId('export-html').click()
    await expect(page.locator('.export-feedback')).toContainText(html)
    const report=readFileSync(html,'utf8')
    expect(report).toContain('Checked against the signed quarterly schedule.')
    expect(report).toContain('AA80')
    expect(report).not.toContain('Revenue!B2')
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('export-btn')).toBeFocused()
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1024,768))
    await page.getByTestId('review-open').click()
    await expect(page.getByRole('dialog')).toContainText('Your decision')
    await page.screenshot({path:testInfo.outputPath('workspace-narrow.png'),animations:'disabled'})
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('review-open')).toBeFocused()
    expect(createHash('sha256').update(readFileSync(source)).digest('hex')).toBe(hash)
  } finally { if(ctx) await teardownApp(ctx) }
})

test('rejects a changed source preview and starts a clean zero-finding review', async () => {
  const root=join(__dirname,'..','tmp','e2e','audit-workspace'); mkdirSync(root,{recursive:true})
  const output=mkdtempSync(join(root,'identity-')); const source=join(output,'changing.xlsx')
  const book=new ExcelJS.Workbook(); const sheet=book.addWorksheet('Revenue'); book.addWorksheet('Archive')
  sheet.getCell('B2').value={formula:'B2+1',result:101}; await book.xlsx.writeFile(source)
  const fingerprint=createHash('sha256').update(readFileSync(source)).digest('hex')
  const ctx=await launchApp()
  try {
    await ctx.app.evaluate(({BrowserWindow,dialog},path)=>{BrowserWindow.getAllWindows()[0].setSize(1440,900);dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]})},source)
    await ctx.page.getByTestId('home-task-audit').click(); await ctx.page.getByTestId('dropzone-browse-btn').click()
    await expect(ctx.page.getByTestId('audit-workspace')).toBeVisible()
    await ctx.page.getByRole('radio',{name:'Confirmed issue',exact:true}).check()
    sheet.getCell('B2').value=200; await book.xlsx.writeFile(source)
    const stale=await ctx.page.evaluate(async ({source,fingerprint}) => window.api.getFileCells(source,'Revenue','A1:C5',fingerprint),{source,fingerprint})
    expect(stale.success).toBe(false)
    await ctx.page.getByRole('button',{name:'Archive',exact:true}).click()
    await expect(ctx.page.locator('.preview-status[role="alert"]')).toContainText('changed')
    await ctx.page.getByTestId('results-rescan-btn').click(); await ctx.page.getByTestId('dropzone-browse-btn').click()
    await expect(ctx.page.getByTestId('audit-workspace')).toBeVisible()
    await expect(ctx.page.locator('.aw-issue')).toHaveCount(0)
    await ctx.page.getByTestId('export-btn').click()
    await expect(ctx.page.getByTestId('export-scope-summary')).toHaveText('0 included · 0 excluded')
    await expect(ctx.page.getByRole('dialog').locator('tbody tr')).toHaveCount(0)
    await expect(ctx.page.getByRole('dialog')).not.toContainText('Confirmed issue')
    const cleanReport=join(output,'clean-review.html')
    await ctx.app.evaluate(({dialog},path)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:path})},cleanReport)
    await ctx.page.getByTestId('export-html').click()
    await expect(ctx.page.locator('.export-feedback')).toContainText(cleanReport)
    expect(readFileSync(cleanReport,'utf8')).toContain('0 of 0 findings included')
  } finally {await teardownApp(ctx)}
})
