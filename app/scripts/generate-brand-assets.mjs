import { readFile, writeFile, mkdir, access } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = fileURLToPath(new URL('../../', import.meta.url))
let sharp
try { sharp = require('sharp') } catch {
  sharp = createRequire(join(root, 'addins/excel/package.json'))('sharp')
}
const check = process.argv.includes('--check')
const addonOnly = process.argv.includes('--addin-only')
const failures = []
let count = 0

export async function generateBrandAssets({ addinOnly = addonOnly } = {}) {
  const master = await readFile(join(root, 'app/resources/brand/mark.svg'), 'utf8')
  const path = master.match(/<path\s+fill="currentColor"\s+d="([^"]+)"\s*\/>/)?.[1]
  if (!path || !master.includes('viewBox="0 0 256 256"')) throw new Error('Invalid brand SVG master')
  const symbol = (color = 'black') => `<path fill="${color}" d="${path}"/>`
  const wrap = (body, viewBox = '0 0 256 256') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body}</svg>\n`
  const tile = wrap(`<rect width="256" height="256" rx="56" fill="black"/>${symbol('white')}`)
  const ios = wrap(`<rect width="256" height="256" fill="black"/>${symbol('white')}`)
  const raster = (svg, size) => sharp(Buffer.from(svg)).resize(size, size).png().toBuffer()
  const exists = async rel => access(join(root, rel)).then(() => true, () => false)
  const output = async (rel, data) => {
    const bytes = Buffer.isBuffer(data) ? data : Buffer.from(data)
    if (check) {
      const current = await readFile(join(root, rel)).catch(() => null)
      if (!current?.equals(bytes)) failures.push(rel)
    } else {
      await mkdir(dirname(join(root, rel)), { recursive: true })
      await writeFile(join(root, rel), bytes)
    }
    count++
  }

  if (await exists('addins/excel/public/assets')) {
    for (const size of [16, 32, 64, 80]) await output(`addins/excel/public/assets/icon-${size}.png`, await raster(tile, size))
  }
  if (addinOnly) return finish()

  // PNG payloads are rendered directly at every target size, never upscaled.
  const sizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024]
  const images = new Map()
  for (const size of sizes) images.set(size, await raster(tile, size))
  const icon = images.get(1024)
  await output('app/resources/icon.png', icon)
  await output('app/resources/brand/icon.svg', tile)
  await output('app/resources/brand/ios-icon.png', await sharp(Buffer.from(ios)).resize(1024,1024).flatten({ background:'black' }).removeAlpha().png().toBuffer())

  function ico(entries) {
    const header = Buffer.alloc(6)
    header.writeUInt16LE(1, 2)
    header.writeUInt16LE(entries.length, 4)
    let offset = 6 + 16 * entries.length
    const directory = entries.map(([size, png]) => {
      const entry = Buffer.alloc(16)
      entry[0] = entry[1] = size === 256 ? 0 : size
      entry.writeUInt16LE(1, 4)
      entry.writeUInt16LE(32, 6)
      entry.writeUInt32LE(png.length, 8)
      entry.writeUInt32LE(offset, 12)
      offset += png.length
      return entry
    })
    return Buffer.concat([header, ...directory, ...entries.map(([, png]) => png)])
  }
  function icns() {
    const types = [['icp4',16],['icp5',32],['icp6',64],['ic07',128],['ic08',256],['ic09',512],['ic10',1024],['ic11',32],['ic12',64],['ic13',256],['ic14',512]]
    const chunks = types.map(([type, size]) => {
      const png = images.get(size)
      const header = Buffer.alloc(8)
      header.write(type, 0, 'ascii')
      header.writeUInt32BE(png.length + 8, 4)
      return Buffer.concat([header, png])
    })
    const header = Buffer.alloc(8)
    header.write('icns', 0, 'ascii')
    header.writeUInt32BE(8 + chunks.reduce((sum, c) => sum + c.length, 0), 4)
    return Buffer.concat([header, ...chunks])
  }
  const windows = ico([16,24,32,48,64,128,256].map(size => [size, images.get(size)]))
  const mac = icns()
  await output('app/resources/icon.ico', windows)
  await output('app/resources/icon.icns', mac)

  const component = `// Generated by app/scripts/generate-brand-assets.mjs from the brand SVG master.\nexport function CellSentryMark({ size = 16, className }: { size?: number; className?: string }) {\n  return (\n    <svg width={size} height={size} viewBox="0 0 256 256" fill="currentColor" className={className} aria-hidden="true">\n      <path d="${path}" />\n    </svg>\n  )\n}\n`
  await output('app/src/components/icons/brand.tsx', component)

  if (await exists('assets')) {
    await output('assets/CellSentry.svg', wrap(symbol('currentColor')))
    await output('assets/CellSentry.png', icon)
    await output('assets/CellSentry.ico', windows)
    await output('assets/CellSentry.icns', mac)
    for (const [name, size] of Object.entries({
      '16x16':16,'16x16@2x':32,'32x32':32,'32x32@2x':64,'64x64':64,
      '128x128':128,'128x128@2x':256,'256x256':256,'256x256@2x':512,
      '512x512':512,'512x512@2x':1024,'1024x1024':1024
    })) await output(`assets/icon.iconset/icon_${name}.png`, images.get(size))
  }
  if (await exists('publish/assets')) {
    await output('publish/assets/CellSentry.png', icon)
    await output('publish/assets/CellSentry.svg', wrap(symbol('currentColor')))
    await output('publish/assets/CellSentry.ico', windows)
    await output('publish/assets/CellSentry.icns', mac)
    for (const [name,size] of Object.entries({ '16x16':16,'16x16@2x':32,'32x32':32,'32x32@2x':64,'64x64':64,'128x128':128,'128x128@2x':256,'256x256':256,'256x256@2x':512,'512x512':512,'512x512@2x':1024,'1024x1024':1024 })) {
      await output(`publish/assets/icon.iconset/icon_${name}.png`, images.get(size))
    }
  }
  if (await exists('website')) {
    await output('website/src/components/brand-mark.tsx', component)
    for (const name of ['logo-icon.svg','logo-mark.svg','favicon.svg']) await output(`website/public/${name}`, tile)
    const favicon = ico([16,32,48].map(size => [size, images.get(size)]))
    await output('website/public/favicon.ico', favicon)
    await output('website/src/app/favicon.ico', favicon)
    // The existing social card keeps its copy, layout and colors; replace only its logo square.
    const cardSource = await readFile(join(root, 'website/public/og-image.png'))
    const replacement = await sharp(Buffer.from(tile)).resize(200, 200).flatten({ background: 'black' }).png().toBuffer()
    const card = await sharp(cardSource).composite([{ input: replacement, left:500, top:160 }]).png().toBuffer()
    if (check) {
      const region = await sharp(cardSource).extract({ left:500,top:160,width:200,height:200 }).removeAlpha().raw().toBuffer()
      const expected = await sharp(replacement).removeAlpha().raw().toBuffer()
      if (!region.equals(expected)) failures.push('website/public/og-image.png')
      count++
    } else await output('website/public/og-image.png', card)
  }
  if (await exists('.claude/design')) {
    const wordmark = await readFile(join(root, 'app/resources/brand/wordmark.svg'), 'utf8')
    const lettering = wordmark.match(/d="([^"]+)"/)?.[1]
    if (!lettering) throw new Error('Missing outlined wordmark')
    for (const color of ['black','white']) {
      const lockup = wrap(`<path fill="${color}" d="${lettering}"/><g transform="translate(-14 8.5) scale(.578125)">${symbol(color)}</g>`, '0 0 749 153')
      await output(`.claude/design/logomark-${color}.svg`, lockup)
      await output(`.claude/design/logomark-${color}.png`, await sharp(Buffer.from(lockup)).resize({ width:749 }).png().toBuffer())
      await output(`.claude/design/mini-icon-${color}.svg`, wrap(symbol(color)))
      await output(`.claude/design/mini-icon-${color}.png`, await raster(wrap(symbol(color)), 256))
    }
    await output('.claude/design/app-icon.svg', tile)
    await output('.claude/design/app-icon.png', icon)
  }
  return finish()
}

function finish() {
  if (failures.length) throw new Error(`Brand assets differ from the SVG master:\n${failures.join('\n')}`)
  console.log(`${check ? 'Verified' : 'Generated'} ${count} brand assets from logo A`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  generateBrandAssets().catch(error => { console.error(error.message); process.exitCode = 1 })
}
